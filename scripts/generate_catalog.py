#!/usr/bin/env python3
"""Generate the human-readable project inventory and source-visibility notes."""
from __future__ import annotations

import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
projects = json.loads((ROOT / "projects.json").read_text(encoding="utf-8"))
groups = defaultdict(list)
for project in projects:
    groups[project["category"]].append(project)

public_count = sum(bool(p.get("sourceAccess") == "public" and p.get("sourceUrl")) for p in projects)
hidden_count = sum(p.get("sourceAccess") == "hidden" for p in projects)
live_count = sum(bool(p.get("liveUrl")) for p in projects)
github_synced = sum(p.get("syncMode") == "github" for p in projects)

lines = [
    "# Project catalog and audit notes",
    "",
    "<!-- Generated by scripts/generate_catalog.py. Edit projects.json, then regenerate. -->",
    "",
    "This file is generated from the same catalog used by README.md and the deployed website.",
    "",
    "## Current inventory",
    "",
    f"- **Project entries:** {len(projects)}",
    f"- **Categories:** {len(groups)}",
    f"- **Public source links:** {public_count}",
    f"- **Source-hidden entries:** {hidden_count}",
    f"- **Live preview URLs:** {live_count}",
    f"- **GitHub-metadata-managed entries:** {github_synced}",
    "",
    "Public repository metadata is refreshed by the scheduled showcase workflow. Existing curated descriptions, private entries, approved live URLs and supplied graphics are preserved. Newly discovered public repositories start with an unlinked live preview and a generated cover until their entry is reviewed.",
    "",
    "Private/unpublished projects are added manually. Their source URL must remain empty; publish only approved public-facing details and graphics, and only add a live URL after checking anonymous access and deployment safety.",
    "",
    "## Entries by category",
    "",
]
for category in sorted(groups):
    lines += [f"### {category}", "", "| Project | Source | Live preview | Stack | Status | Last repository update |", "|---|---|---|---|---|---|"]
    for p in sorted(groups[category], key=lambda item: str(item["title"]).casefold()):
        title = str(p["title"]).replace("|", "\\|")
        if p.get("sourceAccess") == "public" and p.get("sourceUrl"):
            source = f"[Public source]({p['sourceUrl']})"
        else:
            source = "Source hidden"
        if p.get("liveUrl"):
            live = f"[Open preview]({p['liveUrl']})"
        else:
            live = "Not linked"
        status = str(p.get("status", "Not specified")).replace("|", "\\|")
        updated = p.get("updated", "—")
        stack = ", ".join(str(item) for item in (p.get("stack") or [])[:4]).replace("|", "\\|") or "—"
        lines.append(f"| {title} | {source} | {live} | {stack} | {status} | {updated} |")
    lines.append("")

tech_projects: dict[str, list[str]] = defaultdict(list)
tech_labels: dict[str, str] = {}
for project in projects:
    seen_keys: set[str] = set()
    for name in project.get("stack") or []:
        label = re.sub(r"\s+v?\d+(?:\.\d+)*\+?$", "", str(name), flags=re.I).strip()
        key = label.casefold()
        if not key or key in seen_keys:
            continue
        seen_keys.add(key)
        tech_labels.setdefault(key, label)
        tech_projects[key].append(str(project["title"]))
shared_tech = sorted(
    (key for key, titles in tech_projects.items() if len(titles) >= 2),
    key=lambda key: (-len(tech_projects[key]), tech_labels[key].casefold()),
)
lines += [
    "## Technology index",
    "",
    "Technologies used by two or more projects. These match the website's technology filters; version suffixes such as `3.11+` are ignored.",
    "",
    "| Technology | Projects | Used by |",
    "|---|---|---|",
]
for key in shared_tech:
    used_by = ", ".join(sorted(tech_projects[key], key=str.casefold)).replace("|", "\\|")
    lines.append(f"| {tech_labels[key]} | {len(tech_projects[key])} | {used_by} |")
lines.append("")

lines += [
    "## Trust and verification rules",
    "",
    "- A source button is shown only when sourceAccess is public and sourceUrl is a GitHub HTTPS URL.",
    "- A hidden-source entry has an empty sourceUrl. The README generator and deployed gallery both omit its source link.",
    "- Live URL visibility is independent of source visibility. Live links should be set manually only after a public anonymous browser check.",
    "- Private repository data is not fetched by the automatic public inventory sync. Private and unpublished projects remain manual-only entries.",
    "- If a previously listed owned repository disappears from the verified public inventory, the sync fails closed by removing its source URL. The entry and any separately approved live URL remain for manual review.",
    "- Generated covers and feature panels are promotional illustrations, not captured screenshots or proof of production completeness.",
    "- The website footer and navigation link only to the public GitHub profile, this repository and its public docs; they never link to private repositories.",
    "- Never publish credentials, private endpoints, production identifiers, customer data, internal system details, or screenshots copied from private tools.",
    "",
    "## Updating manually curated projects",
    "",
    "1. Edit projects.json and set sourceAccess to public only for an intentionally public GitHub source. For private/unpublished sources use sourceAccess = hidden and sourceUrl = empty string.",
    "2. Add or update screenshots only in approved local asset paths. The entire repository and its README are public.",
    "3. Add liveUrl only after confirming the exact HTTPS URL loads in a signed-out browser and is safe for public visitors.",
    "4. Run python3 scripts/generate_covers.py, python3 scripts/generate_project_panels.py, python3 scripts/generate_readme.py, python3 scripts/generate_catalog.py and the validation/test commands.",
    "5. Commit the catalog and generated README/artwork together.",
    "",
    "Read [PRIVATE_PROJECTS.md](PRIVATE_PROJECTS.md) for the private-project workflow and [ASSET_GUIDELINES.md](ASSET_GUIDELINES.md) for image rules. Website behaviour, filters and the footer are documented in [SITE.md](SITE.md).",
    "",
]
(ROOT / "docs/PROJECT_CATALOG.md").write_text("\n".join(lines), encoding="utf-8")
print(f"Generated docs/PROJECT_CATALOG.md for {len(projects)} entries across {len(groups)} categories.")
